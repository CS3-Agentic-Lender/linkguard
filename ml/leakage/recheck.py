"""Rerun the single-feature leakage check on the ten hostname features.

Reads ml/data/phiusiil_cleaned.csv, works out the ten features with the shared
feature set code and scores each one alone with the check from
ml/leakage/single_feature.py. Writes the table to
ml/reports/leakage_recheck_hostname_features.md. Links are only read as text.
Nothing is opened or fetched.

Run from ml/:  uv run python -m leakage.recheck
"""

import sys
from pathlib import Path

import pandas as pd

from cleaning.storage import CLEANED_CSV_NAME, load_cleaned
from features.hostname import FEATURE_NAMES
from featureset.build import MISSING_CLEANED_HINT, build_feature_set, failure_lines
from leakage.single_feature import FOLDS, LEAKY_ACCURACY_PERCENT, single_feature_accuracy

REPORT_NAME = "leakage_recheck_hostname_features.md"
# The top score in section 2 of ml/reports/leakage_report.md, for comparison.
ORIGINAL_TOP_COLUMN = "URLSimilarityIndex"
ORIGINAL_TOP_PERCENT = 99.67


def recheck_table(features: pd.DataFrame) -> pd.DataFrame:
    """Score each of the ten hostname features alone, sorted high to low, flagging any over 95%."""
    return single_feature_accuracy(features, list(FEATURE_NAMES))


def _flagged_sentence(table: pd.DataFrame) -> str:
    flagged = table.loc[table["Over 95%"], "Column"].tolist()
    count = f"**{len(flagged)} of {len(table)}** features score over {LEAKY_ACCURACY_PERCENT}%"
    if not flagged:
        return f"{count}. So none of them gives the answer away on its own."
    names = ", ".join(f"`{name}`" for name in flagged)
    return f"{count}: {names}. They give the answer away on their own."


def render_report(table: pd.DataFrame, rows: int) -> str:
    """The markdown report: a heading, a short intro, then the table in the layout of the original report."""
    top = table.iloc[0]
    lines = [
        "# Leakage recheck: the ten hostname features",
        "",
        f"Generated by `uv run python -m leakage.recheck` (run from `ml/`) from the cleaned file "
        f"`{CLEANED_CSV_NAME}` ({rows:,} rows). Label 1 is phishing and 0 is legitimate.",
        "The features come from the shared extractor through `ml/featureset/build.py`. "
        "Links were only read as text. None was opened.",
        "",
        "## Single-feature accuracy",
        "",
        "This reruns the single-feature check from section 2 of `ml/reports/leakage_report.md` "
        "on the ten hostname features. "
        f"Each score is the accuracy of a one-split decision tree on that feature alone. "
        f"It is {FOLDS}-fold cross-validated and sorted high to low. "
        f"A feature over {LEAKY_ACCURACY_PERCENT}% is marked YES.",
        "",
        "It uses every cleaned row. That makes it a dataset audit that only flags features. "
        "Any choice of features is made in the feature ranking story, on training rows only.",
        "",
        "A one-split tree learns one threshold. It cannot memorise individual hosts. "
        "So folds that are not grouped by host do not inflate its score.",
        "",
        "This check only finds a column that gives the answer away on its own. "
        "It does not find leakage from the split or the pipeline. "
        "The shared host-grouped split and the Pipeline rule guard against those.",
        "",
        f"{_flagged_sentence(table)} "
        f"The top one here is `{top['Column']}` at {top['Accuracy (%)']:.2f}%. "
        f"The original report's top score was `{ORIGINAL_TOP_COLUMN}` at {ORIGINAL_TOP_PERCENT:.2f}%.",
        "",
        "| Column | Accuracy (%) | Over 95% |",
        "|---|---|---|",
    ]
    for column, accuracy, flagged in zip(table["Column"], table["Accuracy (%)"], table["Over 95%"]):
        lines.append(f"| `{column}` | {accuracy:.2f} | {'YES' if flagged else ''} |")
    return "\n".join(lines) + "\n"


def report_path(ml_dir: Path) -> Path:
    """Where the report is saved, next to ml/reports/leakage_report.md. It is committed."""
    return ml_dir / "reports" / REPORT_NAME


def main(ml_dir: Path) -> int:
    """Build the features, score them and save the report. Returns 1 and saves nothing if the features can't be built."""
    cleaned_path = ml_dir / "data" / CLEANED_CSV_NAME
    if not cleaned_path.is_file():
        print(f"The cleaned file was not found at {cleaned_path}. {MISSING_CLEANED_HINT}")
        return 1
    rows = load_cleaned(cleaned_path)
    result = build_feature_set(rows)
    if result.failures:
        print("\n".join(failure_lines(result.failures)))
        return 1
    table = recheck_table(result.features)
    path = report_path(ml_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_report(table, len(result.features)))
    flagged = int(table["Over 95%"].sum())
    print(f"Scored {len(FEATURE_NAMES)} features on {len(result.features):,} rows. {flagged} over {LEAKY_ACCURACY_PERCENT}%.")
    print(f"Saved to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(__file__).resolve().parents[1]))
